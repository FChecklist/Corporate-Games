// GENERATE (or CHECK) everything the AI reads: registry, OpenAPI, /ai page, /llms.txt, worker bundle.
//   node tools/generate.mjs           rewrite generated/*
//   node tools/generate.mjs --check   change nothing; exit 1 and say what drifted if generated/* is out of date
// Reads the game's code (read only). Needs `bun` for two small scripts that import the game's own modules (constants and access probe).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import adapter from "../games/tambola/adapter.mjs";
import * as content from "../games/tambola/content.mjs";
import { gameRoot, loadSources } from "../games/tambola/extract.mjs";
import { buildRegistry } from "./build.mjs";
import { renderOpenApi, renderAiPage, renderLlmsTxt } from "./render.mjs";
import { renderReadinessBlock, renderDecisionsBlock } from "./render-lifecycle.mjs";

const ROOT = resolve(fileURLToPath(import.meta.url), "../..");
export const OUT = join(ROOT, "generated");
export const FILES = ["actions.generated.json", "openapi.json", "ai.md", "llms.txt", "bundle.generated.mjs"];

export function findBun() {
  const cands = [process.env.BUN, "bun", join(process.env.APPDATA ?? "", "npm", "bun.cmd"), join(process.env.APPDATA ?? "", "npm", "bun")].filter(Boolean);
  for (const c of cands) { const r = spawnSync(c, ["--version"], { shell: true, encoding: "utf8" }); if (r.status === 0) return c; }
  throw new Error("bun was not found. The game runs on bun; install it or set BUN to its path.");
}
function runBun(script, env) {
  const r = spawnSync(findBun(), [script], { shell: true, encoding: "utf8", cwd: ROOT, env: { ...process.env, ...env }, maxBuffer: 64 * 1024 * 1024, timeout: 240000 });
  if (r.status !== 0) throw new Error(`bun ${script} failed:\n${(r.stderr || r.stdout || "").slice(0, 2000)}`);
  return JSON.parse(r.stdout);
}

/** Everything read from the game: its source text, its constants (run by bun) and the access probe (run by bun). */
export function collect({ root = gameRoot() } = {}) {
  return {
    sources: loadSources(root),
    facts: runBun("games/tambola/harness/dump-facts.ts", { CT_GAME_TAMBOLA: root }),
    probe: runBun("games/tambola/harness/probe.ts", { CT_GAME_TAMBOLA: root }),
  };
}

export function generateAll({ root = gameRoot(), collected } = {}) {
  const { sources, facts, probe } = collected ?? collect({ root });
  const registry = buildRegistry({ adapter, content, sources, facts, probe });
  const openapi = renderOpenApi(registry), ai_md = renderAiPage(registry), llms_txt = renderLlmsTxt(registry);
  const bundle = `// GENERATED by tools/generate.mjs. Do not edit.\nexport default ${JSON.stringify({ registry, openapi, ai_md, llms_txt })};\n`;
  return {
    "actions.generated.json": JSON.stringify(registry, null, 2) + "\n",
    "openapi.json": JSON.stringify(openapi, null, 2) + "\n",
    "ai.md": ai_md + "\n", "llms.txt": llms_txt, "bundle.generated.mjs": bundle,
  };
}

// Blocks of the docs that are generated too (between marker comments), so the readiness report and the decisions list can never disagree with the code.
export const DOC_BLOCKS = [
  { file: "docs/GAME_READINESS.md", id: "LIFECYCLE-MATRIX", render: (g) => renderReadinessBlock(g) },
  { file: "docs/OWNER_DECISIONS_AND_RISKS.md", id: "LIFECYCLE-DECISIONS", render: (g) => renderDecisionsBlock(g) },
];
const marks = (id) => [`<!-- GENERATED:${id}:START (written by npm run generate; do not edit by hand) -->`, `<!-- GENERATED:${id}:END -->`];
/** Put `text` between the markers of `id` in `doc` (append the block when the markers are not there yet). */
export function spliceDoc(doc, id, text) {
  const [a, b] = marks(id);
  const start = doc.indexOf(a.split(" (")[0]), end = doc.indexOf(b);
  const block = [a, text, b].join("\n");
  if (start >= 0 && end > start) return doc.slice(0, start) + block + doc.slice(end + b.length);
  return doc.replace(/\s*$/, "") + "\n\n" + block + "\n";
}
/** { "docs/X.md": new full text } for every doc that has a generated block. */
export function generateDocs(registry) {
  const g = registry.games.tambola, out = {};
  for (const d of DOC_BLOCKS) { const p = join(ROOT, d.file); out[d.file] = spliceDoc(out[d.file] ?? (existsSync(p) ? readFileSync(p, "utf8") : ""), d.id, d.render(g)); }
  return out;
}

/** The git commit of the game checkout the pages were generated from (read only). */
export function sourceInfo(root = gameRoot()) {
  const run = (a) => { const r = spawnSync("git", ["-C", root, ...a], { encoding: "utf8" }); return r.status === 0 ? r.stdout.trim() : null; };
  return { game: "tambola", path_note: "checkout used when generating", commit: run(["rev-parse", "--short", "HEAD"]), commit_date: run(["log", "-1", "--format=%cs"]), subject: run(["log", "-1", "--format=%s"]), branch: run(["branch", "--show-current"]), uncommitted_changes: (run(["status", "--porcelain"]) ?? "").length > 0 };
}

/** Which parts of the registry differ (readable list for the drift report). */
export function diffRegistry(a, b, path = "", out = []) {
  if (out.length > 40) return out;
  if (JSON.stringify(a) === JSON.stringify(b)) return out;
  if (a && b && typeof a === "object" && typeof b === "object" && !Array.isArray(a) && !Array.isArray(b)) {
    for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) diffRegistry(a[k], b[k], path ? `${path}.${k}` : k, out);
  } else if (Array.isArray(a) && Array.isArray(b) && a.length === b.length && a.every((x) => x && typeof x === "object" && "id" in x)) {
    a.forEach((x, i) => diffRegistry(x, b[i], `${path}[${x.id}]`, out));
  } else out.push(`${path}: committed ${JSON.stringify(a)?.slice(0, 90)}  ->  game now ${JSON.stringify(b)?.slice(0, 90)}`);
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let files;
  try { files = generateAll(); } catch (e) { console.error(e.message); process.exit(2); }
  if (!check) {
    mkdirSync(OUT, { recursive: true });
    for (const [f, text] of Object.entries(files)) writeFileSync(join(OUT, f), text);
    writeFileSync(join(OUT, "SOURCE.json"), JSON.stringify(sourceInfo(), null, 2) + "\n"); // which game commit this was generated from (informational: not part of the drift comparison)
    const reg = JSON.parse(files["actions.generated.json"]);
    for (const [f, text] of Object.entries(generateDocs(reg))) writeFileSync(join(ROOT, f), text);
    console.log(`Generated ${FILES.length} files in generated/: ${Object.values(reg.games).map((g) => `${g.id}: ${g.actions.length} actions, ${Object.keys(g.routes).length} game routes, ${g.faq.length} FAQ entries`).join("; ")}`);
  } else {
    const stale = [];
    for (const [f, text] of Object.entries(files)) { const p = join(OUT, f); if (!existsSync(p) || readFileSync(p, "utf8") !== text) stale.push(f); }
    const regNow = JSON.parse(files["actions.generated.json"]);
    for (const [f, text] of Object.entries(generateDocs(regNow))) { const p = join(ROOT, f); if (!existsSync(p) || readFileSync(p, "utf8") !== text) stale.push(f); }
    if (stale.length === 0) { console.log("No drift: generated/* matches the game's code."); process.exit(0); }
    console.error("DRIFT: generated/* is out of date with the game or the adapter: " + stale.join(", "));
    if (stale.includes("actions.generated.json")) {
      const was = existsSync(join(OUT, "actions.generated.json")) ? JSON.parse(readFileSync(join(OUT, "actions.generated.json"), "utf8")) : {};
      for (const line of diffRegistry(was, JSON.parse(files["actions.generated.json"]))) console.error("  - " + line);
    }
    console.error("\nWhat to do: read the differences above, then run `npm run generate`, review `git diff generated/`, run `npm test`, commit.");
    process.exit(1);
  }
}
